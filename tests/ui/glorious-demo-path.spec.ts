import { expect, test, type Page } from '@playwright/test'

// Keep this recording independent of the recovery suite's reduced-motion setup.
test.use({
  viewport: { width: 1440, height: 900 },
  reducedMotion: 'no-preference',
  video: 'on',
})

const screenshot = async (page: Page, name: string) => {
  await page.screenshot({ path: `test-results/demo-path/${name}.png`, fullPage: true })
}

test('new-UI demo path records six non-destructive walkthrough steps', async ({ page }) => {
  test.setTimeout(180_000)
  await page.goto('/')

  // 1. Home video and live engine status.
  await expect(page.locator('[aria-label="Mysuru highway"] video')).toBeVisible()
  await expect(page.locator('.gl-status')).toBeVisible()
  await expect(page.locator('.gl-status [role="status"]')).toHaveText(/Running|Degraded|Recovering|Stopped/)
  await screenshot(page, 'step-1-home')

  // 2. Live World enters with motion enabled; wait until all real fleet markers render.
  await page.getByRole('button', { name: 'Live World', exact: true }).click()
  const map = page.getByRole('region', { name: 'Live World map', exact: true })
  await expect(map).toBeVisible()
  const trucks = map.getByRole('button', {
    name: /^Truck T-\d+, .+, \d+(?:\.\d+)? kilometers per hour$/,
  })
  await expect(trucks).toHaveCount(6, { timeout: 20_000 })
  await screenshot(page, 'step-2-live-world')

  // 3. Hover reveals genuine speed, partition, and worker assignment.
  await trucks.first().hover()
  const truckCard = map.getByLabel(/details$/)
  await expect(truckCard).toBeVisible()
  await expect(truckCard.locator('dd').first()).toHaveText(/\d+(?:\.\d+)? km\/h/)
  await expect(truckCard.locator('dd').nth(2)).toHaveText(/Partition \d+ · Worker W\d+/)
  await screenshot(page, 'step-3-truck-card')

  // 4. Drill into a truck's speed chart inside the same analytics window, then back.
  await page.getByRole('button', { name: 'Analytics', exact: true }).click()
  await page.getByRole('button', { name: 'Truck Speeds', exact: true }).click()
  const analytics = page.getByRole('dialog', { name: 'Truck Speeds' })
  const speedList = analytics.getByTestId('analytics-truck-speeds')
  await expect(speedList).toBeVisible()
  const firstTruck = speedList.getByTestId(/^truck-row-.+$/).first()
  await expect(firstTruck).toBeVisible()
  await firstTruck.click()
  await expect(analytics.getByTestId('truck-speed-chart')).toBeVisible()
  await expect(analytics).toHaveCount(1)
  await screenshot(page, 'step-4-truck-speed-chart')
  await analytics.getByRole('button', { name: 'Back', exact: true }).first().click()
  await expect(speedList).toBeVisible()

  // 5. Failed records must show rows or the explicit honest empty state.
  await page.getByRole('button', { name: 'Back to main navigation' }).click()
  await page.getByRole('button', { name: 'Analytics', exact: true }).click()
  await page.getByRole('button', { name: 'Failed Records', exact: true }).click()
  const failedRecords = page.getByRole('dialog', { name: 'Failed Records' })
  const rows = failedRecords.locator('.an-list .an-row')
  const emptyState = failedRecords.getByText('No failed records yet.', { exact: true })
  await expect.poll(async () => (await rows.count()) > 0 || await emptyState.isVisible()).toBe(true)
  await screenshot(page, 'step-5-failed-records')

  // 6. Use the first saved prompt, run its generated/saved pipeline, and open the editor tab.
  await page.getByRole('button', { name: 'Back to main navigation' }).click()
  await page.getByRole('button', { name: 'Pipelines', exact: true }).click()
  const pipelines = page.getByTestId('pipelines-panel')
  await expect(pipelines).toBeVisible()
  await pipelines.getByRole('group', { name: 'Example prompts' }).getByRole('button').first().click()
  await pipelines.getByTestId('ai-generate').click()
  const generated = pipelines.locator('.gl-generated')
  await expect(generated).toBeVisible({ timeout: 60_000 })
  await expect(generated).toContainText(/Generated by AI|Saved example pipeline|Showing a saved example/)
  await pipelines.getByTestId('pipeline-run').click()

  const resultsWindow = page.getByRole('dialog', { name: /Pipeline results/ })
  await expect(resultsWindow.getByTestId('pipeline-results')).toBeVisible({ timeout: 60_000 })
  await expect(resultsWindow.getByTestId('pipeline-results').locator('.gl-run-state'))
    .toHaveText(/Running|Stopped|Failed/, { timeout: 60_000 })
  await screenshot(page, 'step-6-pipeline-results')

  const editorPagePromise = page.waitForEvent('popup')
  await pipelines.getByTestId('open-editor').click()
  const editorPage = await editorPagePromise
  await expect(editorPage).toHaveURL((url) => url.pathname === '/pipelines/editor')
})

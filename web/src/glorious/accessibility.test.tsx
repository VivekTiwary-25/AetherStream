// Reuse the Live World tests' WebGL isolation; axe checks the real map controls and card.
vi.mock('maplibre-gl', () => ({
  setWorkerUrl: vi.fn(),
  addProtocol: vi.fn(),
  removeProtocol: vi.fn(),
  Map: class {
    touchZoomRotate = { disableRotation() {} }
    on() { return this }
    resize() {}
    remove() {}
  },
}))
vi.mock('maplibre-gl/dist/maplibre-gl-worker.mjs?worker&url', () => ({ default: 'map-worker.js' }))
vi.mock('pmtiles', () => ({ Protocol: class { tile = vi.fn() } }))
vi.mock('./map/useLiveFleet', () => ({
  useLiveFleet: () => ({
    trucks: [{ truckId: 'truck-001', speedKmh: 35, status: 'DRIVING', x: 0, y: 0, heading: 0 }],
    timeScale: 10, running: true, fresh: false, controlsFresh: false, error: null,
  }),
}))

class ResizeObserverStub { observe() {} unobserve() {} disconnect() {} }

const respond = (status: number, body: unknown) => Promise.resolve(new Response(JSON.stringify(body), {
  status, headers: { 'Content-Type': 'application/json' },
}))

const runningDashboard = {
  ...initialDashboardState,
  socketStatus: 'connected' as const,
  execution: {
    id: 'exec-1', pipelineId: 'fleet', pipelineVersion: 1, state: 'RUNNING' as const,
    generation: 1, restoredFromCheckpoint: null, lastCompletedCheckpoint: 0,
    createdAt: '2026-11-20T00:00:00Z',
  },
}

afterEach(() => {
  cleanup()
  vi.restoreAllMocks()
  vi.unstubAllGlobals()
  window.localStorage.clear()
  window.sessionStorage.clear()
  window.history.replaceState(null, '', '/')
})

async function expectAccessible(container: HTMLElement) {
  const results = await axe(container)
  expect(results.violations).toEqual([])
}

function TruckSpeedsOpener() {
  const windows = useWindows()
  return <button type="button" onClick={() => windows.open('analytics.speeds', {
    title: 'Truck Speeds', render: () => <AnalyticsPanel id="truck-speeds" />,
  })}>Open Truck Speeds</button>
}

describe('Glorious accessibility', () => {
  it('checks the sidebar', async () => {
    const { container } = render(<div className="glorious-app"><WindowManager><Sidebar screen="live" navigate={() => undefined} /></WindowManager></div>)
    await expectAccessible(container)
  })

  it('checks a Truck Speeds glass window', async () => {
    const { container } = render(<div className="glorious-app"><DashboardContext.Provider value={initialDashboardState}>
      <WindowManager><TruckSpeedsOpener /></WindowManager>
    </DashboardContext.Provider></div>)
    fireEvent.click(screen.getByRole('button', { name: 'Open Truck Speeds' }))
    await expectAccessible(container)
  })

  it('checks Logs & Recovery', async () => {
    const { container } = render(<div className="glorious-app"><DashboardContext.Provider value={initialDashboardState}>
      <WindowManager><LogsRecovery /></WindowManager>
    </DashboardContext.Provider></div>)
    await expectAccessible(container)
  })

  it('checks the Pipelines panel', async () => {
    const { container } = render(<div className="glorious-app"><WindowManager><PipelinesPanel /></WindowManager></div>)
    await expectAccessible(container)
  })

  it('checks the Ask AI offline saved-example review', async () => {
    vi.stubGlobal('fetch', vi.fn(() => respond(503, {})))
    const example = EXAMPLES[0]!
    const { container } = render(<div className="glorious-app"><WindowManager><PipelinesPanel /></WindowManager></div>)
    fireEvent.click(screen.getByRole('button', { name: example.prompt }))
    await act(async () => { fireEvent.click(screen.getByTestId('ai-generate')) })
    expect(screen.getByText('AI is offline - this is a saved example, not generated by AI')).toBeTruthy()
    expect(screen.getByText('Saved example')).toBeTruthy()
    expect(screen.getByRole('list', { name: `Steps of ${example.pipeline.name}` })).toBeTruthy()
    await expectAccessible(container)
  })

  it.each(['running with results', 'results-request error'] as const)('checks the editor results window: %s', async (state) => {
    vi.stubGlobal('ResizeObserver', ResizeObserverStub)
    const capture = JSON.parse(partitionCaptureJson) as {
      run: { status: number; body: { runId: string } }
      polls: { status: number; body: ResultsPage }[]
    }
    const results = capture.polls[1]!
    vi.stubGlobal('fetch', vi.fn((url: string) => {
      if (url.endsWith('/fields')) return respond(200, { fields: [{ name: 'speedKmh', type: 'number' }] })
      if (url.endsWith('/runs')) return respond(capture.run.status, capture.run.body)
      return state === 'results-request error' ? respond(502, {}) : respond(results.status, results.body)
    }))
    const example = EXAMPLES.find((item) => item.id === 'partition')!
    window.history.replaceState(null, '', '/pipelines/editor')
    let container!: HTMLElement
    await act(async () => {
      ;({ container } = render(<div className="glorious-app"><WindowManager><EditorPage /></WindowManager></div>))
    })
    fireEvent.change(screen.getByLabelText('Load example'), { target: { value: example.id } })
    await act(async () => { fireEvent.click(screen.getByTestId('pipeline-run')) })
    const dialog = within(screen.getByRole('dialog', { name: `Pipeline results - ${example.pipeline.name}` }))
    if (state === 'running with results') {
      expect(dialog.getByText('Running')).toBeTruthy()
      expect(dialog.getByRole('table').textContent).toContain('truck-002')
      expect(dialog.getByRole('columnheader', { name: 'Time' })).toBeTruthy()
    } else {
      expect(dialog.getByText('Disconnected')).toBeTruthy()
      expect(dialog.getByRole('alert').textContent).toContain('Pipeline service unavailable')
      expect(dialog.getByText('Results unavailable. Waiting to reconnect.')).toBeTruthy()
    }
    await expectAccessible(container)
  })

  it('checks the Live World stale truck card with unavailable ownership', async () => {
    vi.stubGlobal('ResizeObserver', ResizeObserverStub)
    vi.stubGlobal('fetch', vi.fn((url: string) => respond(200, url.endsWith('routes.geojson') ? { features: [] } : [])))
    let container!: HTMLElement
    await act(async () => {
      ;({ container } = render(<div className="glorious-app"><DashboardContext.Provider value={{
        ...runningDashboard, socketStatus: 'disconnected',
        // Full WorkerInfo: `npm run build` runs tsc -b over test files too (web.Dockerfile).
        workers: [{ workerId: 'worker-1', alive: true, state: 'RUNNING', partitions: [0, 1, 2, 3, 4, 5], sourceQueue: { size: 0, capacity: 1000 }, sinkQueue: { size: 0, capacity: 1000 }, backpressured: false, recordsPerSec: 0, lastHeartbeatMs: 0 }],
      }}><LiveWorld /></DashboardContext.Provider></div>))
    })
    fireEvent.click(screen.getByRole('button', { name: /kilometers per hour/ }))
    expect(screen.getByText('Last known: DRIVING')).toBeTruthy()
    expect(screen.getByText(/Partition \d · Worker unavailable/)).toBeTruthy()
    expect(screen.getByRole('button', { name: 'Close truck details' })).toBeTruthy()
    await expectAccessible(container)
  })

  it('checks the StatusPill last-reported state', async () => {
    const { container } = render(<div className="glorious-app"><DashboardContext.Provider value={{
      ...runningDashboard, socketStatus: 'disconnected',
      flow: { eventsPerSec: 42, byPartition: {}, rejectedPerSec: 0, latePerSec: 0 },
    }}><StatusPill /></DashboardContext.Provider></div>)
    expect(screen.getByRole('status').textContent).toBe('Last reported: Running')
    expect(screen.getByLabelText('Event rate unavailable')).toBeTruthy()
    await expectAccessible(container)
  })

  it('checks the Failed Records empty state and empty kind filters', async () => {
    const { container } = render(<div className="glorious-app"><DashboardContext.Provider value={runningDashboard}>
      <WindowManager><AnalyticsPanel id="failed-records" /></WindowManager>
    </DashboardContext.Provider></div>)
    for (const [name, message] of [
      ['All', 'No failed records yet.'],
      ['Rejected', 'No rejected records yet.'],
      ['Late', 'No late records yet.'],
    ]) {
      fireEvent.click(screen.getByRole('button', { name }))
      expect(screen.getByRole('button', { name, pressed: true })).toBeTruthy()
      expect(screen.getByText(message)).toBeTruthy()
      await expectAccessible(container)
    }
  })
})

import { useEffect, useId, useState } from 'react'
import { ClayButton } from '../shell/ClayButton'
import { GlassSurface } from '../shell/GlassSurface'
import { describeError, generatePipeline, type ErrorView, type GenerateResponse } from './api'
import { ErrorList } from './ErrorList'
import { EXAMPLES } from './examples'
import { storeHandoff } from './model'
import { PipelineReview } from './PipelineReview'
import { useRunPipeline } from './useRunPipeline'
import { ExternalIcon } from './ExternalIcon'
import { openEditor } from './links'
import './pipelines.css'

function Thinking() {
  const [seconds, setSeconds] = useState(0)
  useEffect(() => {
    const started = Date.now()
    const timer = setInterval(() => setSeconds(Math.floor((Date.now() - started) / 1000)), 1000)
    return () => clearInterval(timer)
  }, [])
  return <div className="gl-thinking" role="status">
    <span className="gl-thinking__dots" aria-hidden="true"><span /><span /><span /></span>
    <span>Thinking... {seconds} s <span className="gl-muted">(usually 10-30 s)</span></span>
  </div>
}

export function PipelinesPanel() {
  const promptId = useId()
  const [prompt, setPrompt] = useState('')
  const [generating, setGenerating] = useState(false)
  const [generated, setGenerated] = useState<GenerateResponse | null>(null)
  const [error, setError] = useState<ErrorView | null>(null)
  const [handoffError, setHandoffError] = useState('')
  const runner = useRunPipeline()

  const generate = async () => {
    if (!prompt.trim() || generating) return
    setGenerating(true)
    setError(null)
    setGenerated(null)
    runner.clearError()
    try { setGenerated(await generatePipeline(prompt.trim())) } catch (caught) { setError(describeError(caught, 'ai')) } finally { setGenerating(false) }
  }

  const openInEditor = () => {
    if (!generated) return
    if (!storeHandoff(generated.pipeline)) { setHandoffError('Could not hand the pipeline to the editor (browser storage is blocked).'); return }
    setHandoffError('')
    openEditor('?from=ai')
  }

  return <div className="gl-track-page gl-pipelines">
    <GlassSurface strong className="gl-pipelines__panel">
      <section data-testid="pipelines-panel" aria-labelledby={`${promptId}-title`}>
        <header className="gl-pipelines__header">
          <h1 id={`${promptId}-title`}>Pipelines</h1>
          <button type="button" className="gl-clay-button gl-pipelines__open" data-testid="open-editor" onClick={() => openEditor()}>
            <ExternalIcon /><span>Open Editor</span><span className="gl-sr-only"> (opens in a new tab)</span>
          </button>
        </header>

        <h2 className="gl-pipelines__sub">Ask AI</h2>
        <label htmlFor={promptId} className="gl-label">Describe what you want to see from the live truck stream</label>
        <textarea id={promptId} data-testid="ai-prompt" className="gl-textarea" rows={4} value={prompt}
          placeholder="e.g. Alert me when any truck goes over 60 km/h"
          onChange={(event) => setPrompt(event.target.value)}
          onKeyDown={(event) => { if (event.key === 'Enter' && (event.ctrlKey || event.metaKey)) void generate() }} />
        <div className="gl-chips" role="group" aria-label="Example prompts">
          {EXAMPLES.map((example) => <button type="button" key={example.id} className="gl-chip" onClick={() => setPrompt(example.prompt)}>{example.prompt}</button>)}
        </div>
        <div className="gl-actions">
          <ClayButton data-testid="ai-generate" onClick={() => void generate()} disabled={generating || !prompt.trim()}>{generating ? 'Generating...' : 'Generate'}</ClayButton>
          {generating && <Thinking />}
        </div>
        {error && <ErrorList error={error} />}

        {generated && <div className="gl-generated" aria-live="polite">
          {generated.source === 'example' && <p className="gl-alert gl-alert--warn" role="status"><strong>{generated.note ?? 'Showing a saved example: AI was unavailable'}</strong></p>}
          <h2 className="gl-pipelines__sub">{generated.pipeline.name}</h2>
          <p className="gl-muted gl-small">
            {generated.source === 'ai' ? `Generated by AI${generated.model ? ` (${generated.model})` : ''} in ${(generated.ms / 1000).toFixed(1)} s. Review before running.` : 'Saved example pipeline. Review before running.'}
          </p>
          <PipelineReview pipeline={generated.pipeline} />
          <div className="gl-actions">
            <ClayButton data-testid="pipeline-run" onClick={() => void runner.run(generated.pipeline)} disabled={runner.running}>{runner.running ? 'Starting...' : 'Run'}</ClayButton>
            <ClayButton onClick={openInEditor}><ExternalIcon /><span>Open in editor</span><span className="gl-sr-only"> (opens in a new tab)</span></ClayButton>
          </div>
          {handoffError && <p className="gl-alert gl-alert--error" role="alert">{handoffError}</p>}
          {runner.error && <ErrorList error={runner.error} />}
        </div>}
      </section>
    </GlassSurface>
  </div>
}

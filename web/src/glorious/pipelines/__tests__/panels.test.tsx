describe('EditorPage', () => {
  afterEach(() => { cleanup(); vi.useRealTimers(); vi.restoreAllMocks(); vi.unstubAllGlobals(); window.localStorage.clear(); window.sessionStorage.clear(); window.history.replaceState(null, '', '/') })

  it.each([
    ['average', averageCaptureJson],
    ['partition', partitionCaptureJson],
  ])('validates and runs the editor’s %s example using captured API responses', async (exampleId, captureJson) => {
    vi.useFakeTimers()
    vi.stubGlobal('ResizeObserver', FakeResizeObserver)
    const example = EXAMPLES.find((item) => item.id === exampleId)!
    // Exact run/validation bodies and first two polls copied from the live proof captures.
    const { validation, run, polls } = JSON.parse(captureJson) as {
      validation: { status: number; body: unknown }
      run: { status: number; body: { runId: string } }
      polls: { status: number; body: ResultsPage }[]
    }
    let pollIndex = 0
    const fetchMock = vi.fn((url: string, init?: RequestInit) => {
      if (url.endsWith('/fields')) return respond(200, { fields: [{ name: 'speedKmh', type: 'number' }] })
      if (url.endsWith('/validate') || url.endsWith('/runs')) {
        // Both endpoints accept the bare pipeline, preserving node ids and from/to edges.
        expect(init?.method).toBe('POST')
        expect(JSON.parse(init!.body as string)).toEqual(example.pipeline)
        return url.endsWith('/validate') ? respond(validation.status, validation.body) : respond(run.status, run.body)
      }
      const request = new URL(url, window.location.origin)
      expect(request.pathname).toBe(`/api/glorious/pipelines/runs/${run.body.runId}/results`)
      const after = request.searchParams.get('after')!
      if (!/^\d+$/.test(after)) return respond(400, { valid: false, errors: [{ message: 'after must be non-negative' }] })
      expect(init?.signal).toBeInstanceOf(AbortSignal)
      const page = polls[Math.min(pollIndex++, polls.length - 1)]!
      return respond(page.status, { ...page.body, results: page.body.results.filter((result) => result.seq > Number(after)) })
    })
    vi.stubGlobal('fetch', fetchMock)
    window.history.replaceState(null, '', '/pipelines/editor')
    await act(async () => { render(<div className="glorious-app"><WindowManager><EditorPage /></WindowManager></div>) })
    fireEvent.change(screen.getByLabelText('Load example'), { target: { value: exampleId } })
    await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Validate' })) })
    expect(screen.getByRole('status').textContent).toContain('This pipeline can run.')
    await act(async () => { fireEvent.click(screen.getByTestId('pipeline-run')) })
    expect(screen.getByRole('dialog', { name: `Pipeline results - ${example.pipeline.name}` })).toBeTruthy()
    expect(screen.getByText('Running')).toBeTruthy()
    expect(screen.getByText('Events in:').textContent).toBe('Events in: 0')
    expect(screen.getByText('Buffered results:').textContent).toBe('Buffered results: 0')
    expect(screen.getByText('Waiting for matching events. No results yet.')).toBeTruthy()
    for (let index = 1; index < polls.length; index++) {
      await act(async () => { vi.advanceTimersByTime(1000) })
    }
    const lastPage = polls[polls.length - 1]!.body
    const rows = polls.flatMap((poll) => poll.body.results)
    expect(screen.getByText('Running')).toBeTruthy()
    expect(screen.getByText('Events in:').textContent).toBe(`Events in: ${lastPage.eventsIn}`)
    expect(screen.getByText('Buffered results:').textContent).toBe(`Buffered results: ${rows.length}`)
    expect(screen.queryByText('Disconnected')).toBeNull()
    expect(screen.queryByText('The pipeline is not valid')).toBeNull()
    if (exampleId === 'partition') {
      expect(screen.getByRole('table').textContent).toContain('truck-002')
      expect(screen.getByRole('table').textContent).toContain('Partition 2 speeds')
    } else {
      // The real average-speed capture contains events but no emitted rows.
      expect(screen.queryByRole('table')).toBeNull()
      expect(screen.getByText('Waiting for matching events. No results yet.')).toBeTruthy()
    }
    await act(async () => { vi.advanceTimersByTime(1000) })
    const cursor = rows.length ? Math.max(...rows.map((row) => row.seq)) : 0
    expect(fetchMock).toHaveBeenLastCalledWith(expect.stringContaining(`/results?after=${cursor}`), expect.anything())
    expect(screen.getByText('Buffered results:').textContent).toBe(`Buffered results: ${rows.length}`)
  })

  it.each([200, 400])('shows validation errors on the node for HTTP %s', async (status) => {
    vi.stubGlobal('ResizeObserver', FakeResizeObserver)
    vi.stubGlobal('fetch', vi.fn((url: string) => url.endsWith('/fields')
      ? Promise.resolve(new Response('', { status: 502 }))
      : respond(status, { valid: false, errors: [{ nodeId: 'n2', message: 'value must be a number' }] })))
    window.localStorage.setItem('glorious.pipelines.fromAi', JSON.stringify(EXAMPLES[0]!.pipeline))
    window.history.replaceState(null, '', '/pipelines/editor?from=ai')
    await act(async () => { render(<WindowManager><EditorPage /></WindowManager>) })
    expect((screen.getByLabelText('Pipeline name') as HTMLInputElement).value).toBe('Speeding alert')
    expect(screen.getByText('Loaded the pipeline handed over from Pipelines.')).toBeTruthy()
    expect(screen.getByText(/Pipeline service unavailable: field list comes from the shared contract/)).toBeTruthy()
    expect(screen.getAllByRole('button', { name: /^Add / }).map((button) => button.textContent)).toEqual(['Add Filter', 'Add Pick Field', 'Add Window Average', 'Add Threshold Alert', 'Add Output'])
    await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Validate' })) })
    expect(screen.getByLabelText('Errors on n2').textContent).toContain('value must be a number')
  })

  it('labels contract fields when the field API returns no usable metadata', async () => {
    vi.stubGlobal('ResizeObserver', FakeResizeObserver)
    vi.stubGlobal('fetch', vi.fn(() => respond(200, { fields: [] })))
    await act(async () => { render(<WindowManager><EditorPage /></WindowManager>) })
    fireEvent.click(screen.getByRole('button', { name: 'Add Filter' }))
    expect(screen.getByText(/returned no usable fields; showing shared contract fields/)).toBeTruthy()
    expect(screen.getByRole('option', { name: 'speedKmh (number)' })).toBeTruthy()
  })

  it('shows validation service failure without claiming the pipeline is valid', async () => {
    vi.stubGlobal('ResizeObserver', FakeResizeObserver)
    vi.stubGlobal('fetch', vi.fn((url: string) => url.endsWith('/fields')
      ? respond(200, { fields: [{ name: 'speedKmh', type: 'number' }] })
      : respond(503, {})))
    await act(async () => { render(<WindowManager><EditorPage /></WindowManager>) })
    fireEvent.click(screen.getByRole('button', { name: 'Add Filter' }))
    await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Validate' })) })
    expect(screen.getByRole('alert').textContent).toContain('Pipeline service unavailable')
    expect(screen.queryByText('Valid.')).toBeNull()
    expect(screen.queryByTestId('pipeline-results')).toBeNull()
    expect(screen.queryByText(/showing shared contract fields/)).toBeNull()
  })

  it.each(['refresh', 'back'] as const)('restores this tab’s edited pipeline after %s', async (navigation) => {
    vi.stubGlobal('ResizeObserver', FakeResizeObserver)
    vi.stubGlobal('fetch', vi.fn(() => respond(200, { fields: [] })))
    window.localStorage.setItem('glorious.pipelines.fromAi', JSON.stringify(EXAMPLES[0]!.pipeline))
    window.history.replaceState(null, '', '/pipelines/editor?from=ai')
    let editor: RenderResult
    await act(async () => { editor = render(<WindowManager><EditorPage /></WindowManager>) })
    fireEvent.change(screen.getByLabelText('Pipeline name'), { target: { value: 'My edited pipeline' } })
    fireEvent.click(screen.getByRole('button', { name: 'Add Pick Field' }))
    editor!.unmount()
    // A later handoff from another tab must not replace this editor’s draft on refresh.
    window.localStorage.setItem('glorious.pipelines.fromAi', JSON.stringify(EXAMPLES[1]!.pipeline))
    if (navigation === 'back') {
      window.history.replaceState(null, '', '/pipelines')
      window.history.replaceState(null, '', '/pipelines/editor')
    }
    await act(async () => { render(<WindowManager><EditorPage /></WindowManager>) })
    expect((screen.getByLabelText('Pipeline name') as HTMLInputElement).value).toBe('My edited pipeline')
    expect(screen.getByText('n4')).toBeTruthy()
  })

  it.each([200, 400])('ignores an outdated validation response (%s) after editing', async (status) => {
    vi.stubGlobal('ResizeObserver', FakeResizeObserver)
    let finish!: (response: Response) => void
    // The project targets ES2022, which does not include Promise.withResolvers.
    vi.stubGlobal('fetch', vi.fn((url: string) => url.endsWith('/fields')
      ? respond(200, { fields: [] })
      : new Promise<Response>((resolve) => { finish = resolve })))
    window.localStorage.setItem('glorious.pipelines.fromAi', JSON.stringify(EXAMPLES[0]!.pipeline))
    window.history.replaceState(null, '', '/pipelines/editor?from=ai')
    await act(async () => { render(<WindowManager><EditorPage /></WindowManager>) })
    fireEvent.click(screen.getByRole('button', { name: 'Validate' }))
    fireEvent.change(screen.getByLabelText('Pipeline name'), { target: { value: 'Changed during validation' } })
    await act(async () => {
      finish(await respond(status, status === 200 ? { valid: true, errors: [] } : { valid: false, errors: [{ nodeId: 'n2', message: 'outdated validation error' }] }))
    })
    expect(screen.queryByText('Valid.')).toBeNull()
    expect(screen.queryByText(/outdated validation error/)).toBeNull()
    expect((screen.getByRole('button', { name: 'Validate' }) as HTMLButtonElement).disabled).toBe(false)
  })
})

describe('pipeline results lifecycle', () => {
  afterEach(() => { cleanup(); vi.useRealTimers(); vi.restoreAllMocks(); vi.unstubAllGlobals() })

  it.each([0, 200])('opens the new run when the old window closes during start (%s ms)', async (closingDelay) => {
    vi.useFakeTimers()
    vi.stubGlobal('ResizeObserver', FakeResizeObserver)
    let finish!: (response: Response) => void
    // The project targets ES2022, which does not include Promise.withResolvers.
    let starts = 0
    const fetchMock = vi.fn((url: string) => {
      if (url.endsWith('/runs')) {
        starts++
        return starts === 1 ? respond(200, { runId: 'r1' }) : new Promise<Response>((resolve) => { finish = resolve })
      }
      return respond(200, { runId: url.includes('/r2/') ? 'r2' : 'r1', state: 'STOPPED', eventsIn: url.includes('/r2/') ? 22 : 11, results: [] })
    })
    vi.stubGlobal('fetch', fetchMock)
    render(<div className="glorious-app"><WindowManager><RunButton /></WindowManager></div>)
    await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Run test pipeline' })) })
    expect(screen.getByText('11')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Run test pipeline' }))
    fireEvent.click(screen.getByRole('button', { name: 'Close Pipeline results - Speeding alert' }))
    await act(async () => { vi.advanceTimersByTime(closingDelay) })
    await act(async () => { finish(await respond(200, { runId: 'r2' })) })
    expect(screen.getByRole('dialog', { name: 'Pipeline results - Speeding alert' })).toBeTruthy()
    expect(screen.getByText('22')).toBeTruthy()
    expect(screen.queryByText('11')).toBeNull()
  })

  it('marks failed polling as disconnected and recovers without duplicating rows or leaking timers', async () => {
    vi.useFakeTimers()
    const warn = vi.spyOn(console, 'warn').mockImplementation(() => {})
    let polls = 0
    const fetchMock = vi.fn(() => {
      polls++
      return polls === 2
        ? respond(502, { error: 'unavailable' })
        : respond(200, { runId: 'r1', state: 'RUNNING', eventsIn: polls, results: [{ seq: 1, ts: 1, output: 'Live output', kind: 'row', data: { truckId: 'Truck A' } }] })
    })
    vi.stubGlobal('fetch', fetchMock)
    let results: RenderResult
    await act(async () => { results = render(<ResultsView runId="r1" />) })
    expect(screen.getByText('Running')).toBeTruthy()
    await act(async () => { vi.advanceTimersByTime(1000) })
    expect(screen.getByText('Disconnected')).toBeTruthy()
    expect(screen.queryByText('Running')).toBeNull()
    expect(screen.getByRole('alert').textContent).toContain('Pipeline service unavailable')
    expect(screen.getAllByText('Truck A')).toHaveLength(1)
    await act(async () => { vi.advanceTimersByTime(4999) })
    expect(fetchMock).toHaveBeenCalledTimes(2)
    await act(async () => { vi.advanceTimersByTime(1) })
    expect(screen.getByText('Running')).toBeTruthy()
    expect(screen.queryByText('Disconnected')).toBeNull()
    expect(screen.getAllByText('Truck A')).toHaveLength(1)
    expect(warn).toHaveBeenCalledTimes(1)
    results!.unmount()
    await act(async () => { vi.advanceTimersByTime(5000) })
    expect(fetchMock).toHaveBeenCalledTimes(3)
  })

  it('caps outage retries, preserves the cursor, and resets backoff after recovery', async () => {
    vi.useFakeTimers()
    const warn = vi.spyOn(console, 'warn').mockImplementation(() => {})
    let polls = 0
    const fetchMock = vi.fn(() => {
      polls++
      return [2, 3, 4, 5, 7].includes(polls)
        ? respond(503, {})
        : respond(200, { runId: 'r1', state: polls === 8 ? 'STOPPED' : 'RUNNING', eventsIn: polls, results: [{ seq: 7, ts: 1, output: 'Saved output', kind: 'row', data: {} }] })
    })
    vi.stubGlobal('fetch', fetchMock)
    await act(async () => { render(<ResultsView runId="r1" />) })
    await act(async () => { vi.advanceTimersByTime(1000) })
    expect(screen.getByRole('alert').textContent).toContain('Pipeline service unavailable')
    for (const delay of [5000, 10000, 15000, 15000]) {
      const previousCalls = fetchMock.mock.calls.length
      await act(async () => { vi.advanceTimersByTime(delay - 1) })
      expect(fetchMock).toHaveBeenCalledTimes(previousCalls)
      await act(async () => { vi.advanceTimersByTime(1) })
      expect(fetchMock).toHaveBeenCalledTimes(previousCalls + 1)
    }
    expect(screen.getByText('Running')).toBeTruthy()
    expect(screen.queryByRole('alert')).toBeNull()
    expect(screen.getAllByText('Saved output')).toHaveLength(1)
    expect(warn).toHaveBeenCalledTimes(1)
    expect(fetchMock).toHaveBeenLastCalledWith(expect.stringContaining('after=7'), expect.anything())
    await act(async () => { vi.advanceTimersByTime(1000) })
    expect(screen.getByText('Disconnected')).toBeTruthy()
    expect(warn).toHaveBeenCalledTimes(2)
    await act(async () => { vi.advanceTimersByTime(4999) })
    expect(fetchMock).toHaveBeenCalledTimes(7)
    await act(async () => { vi.advanceTimersByTime(1) })
    expect(screen.getByText('Stopped')).toBeTruthy()
    await act(async () => { vi.advanceTimersByTime(30000) })
    expect(fetchMock).toHaveBeenCalledTimes(8)
  })

  it.each([404, 503])('shows an initial polling failure without inventing counts or rows (%s)', async (status) => {
    vi.useFakeTimers()
    vi.spyOn(console, 'warn').mockImplementation(() => {})
    const fetchMock = vi.fn((url: string) => {
      expect(new URL(url, window.location.origin).searchParams.get('after')).toBe('0')
      return respond(status, {})
    })
    vi.stubGlobal('fetch', fetchMock)
    await act(async () => { render(<ResultsView runId="r1" />) })
    expect(screen.getByText('Disconnected')).toBeTruthy()
    expect(screen.getByRole('alert').textContent).toContain(status === 404 ? 'Run not found' : 'Pipeline service unavailable')
    expect(screen.getByText('Events in:').textContent).toBe('Events in: -')
    expect(screen.getByText('Buffered results:').textContent).toBe('Buffered results: -')
    expect(screen.getByText('Results unavailable. Waiting to reconnect.')).toBeTruthy()
    expect(screen.queryByRole('table')).toBeNull()
  })

  it('reports a rejected results cursor without calling the validated pipeline invalid', async () => {
    vi.useFakeTimers()
    vi.spyOn(console, 'warn').mockImplementation(() => {})
    vi.stubGlobal('fetch', vi.fn(() => respond(400, { valid: false, errors: [{ message: 'after must be non-negative' }] })))
    await act(async () => { render(<ResultsView runId="validated-run" />) })
    expect(screen.getByText('Disconnected')).toBeTruthy()
    expect(screen.getByRole('alert').textContent).toBe('Could not fetch pipeline results: after must be non-negative')
    expect(screen.queryByText('The pipeline is not valid')).toBeNull()
    expect(screen.getByText('Events in:').textContent).toBe('Events in: -')
  })

  it.each(['STOPPED', 'FAILED'] as const)('renders terminal state %s and stops polling', async (state) => {
    vi.useFakeTimers()
    const fetchMock = vi.fn(() => respond(200, { runId: 'r1', state, error: state === 'FAILED' ? 'Stream unavailable' : undefined, eventsIn: 0, results: [] }))
    vi.stubGlobal('fetch', fetchMock)
    await act(async () => { render(<ResultsView runId="r1" />) })
    expect(screen.getByText(state === 'STOPPED' ? 'Stopped' : 'Failed')).toBeTruthy()
    if (state === 'FAILED') expect(screen.getByRole('alert').textContent).toContain('Stream unavailable')
    expect(screen.getByText('No results.')).toBeTruthy()
    expect(screen.queryByRole('table')).toBeNull()
    expect((screen.getByRole('button', { name: 'Stop' }) as HTMLButtonElement).disabled).toBe(true)
    await act(async () => { vi.advanceTimersByTime(30000) })
    expect(fetchMock).toHaveBeenCalledTimes(1)
  })

  it('does not claim a run stopped when the stop request fails', async () => {
    vi.useFakeTimers()
    vi.stubGlobal('fetch', vi.fn((url: string) => url.endsWith('/stop')
      ? respond(503, {})
      : respond(200, { runId: 'r1', state: 'RUNNING', eventsIn: 0, results: [] })))
    await act(async () => { render(<ResultsView runId="r1" />) })
    await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Stop' })) })
    expect(screen.getByRole('alert').textContent).toContain('Could not stop: Pipeline service unavailable')
    expect(screen.getByText('Running')).toBeTruthy()
    expect(screen.queryByText('Stopped')).toBeNull()
  })

  it('does not overlap requests and ignores a page received after unmount', async () => {
    vi.useFakeTimers()
    let finish!: (response: Response) => void
    const fetchMock = vi.fn<(url: string, init?: RequestInit) => Promise<Response>>(() => new Promise<Response>((resolve) => { finish = resolve }))
    vi.stubGlobal('fetch', fetchMock)
    const results = render(<ResultsView runId="r1" />)
    const signal = fetchMock.mock.calls[0]![1]!.signal!
    await act(async () => { vi.advanceTimersByTime(30000) })
    expect(fetchMock).toHaveBeenCalledTimes(1)
    results.unmount()
    expect(signal.aborted).toBe(true)
    await act(async () => { finish(await respond(200, { runId: 'r1', state: 'RUNNING', eventsIn: 1, results: [] })) })
    await act(async () => { vi.advanceTimersByTime(30000) })
    expect(fetchMock).toHaveBeenCalledTimes(1)
    expect(vi.getTimerCount()).toBe(0)
  })
})
